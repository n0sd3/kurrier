// Regenerates apple-touch-startup-image assets for the iOS splash screen.
// Safari doesn't derive these from the manifest/icons like the rest of the
// PWA metadata does — it only matches static images against exact
// device-width/height/dpr media queries, so we render one PNG per device
// class (portrait + landscape) instead of a single responsive asset.
// Run: node scripts/generate-splash-screens.mjs
import sharp from "sharp";
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PUBLIC_DIR = path.join(__dirname, "..", "public");
const MARK_SVG = path.join(PUBLIC_DIR, "icons", "kurrier-mark.svg");
const OUT_DIR = path.join(PUBLIC_DIR, "icons", "splash");
const MANIFEST_OUT = path.join(__dirname, "..", "lib", "apple-splash-screens.ts");

const BACKGROUND = "#ffffff";
const MARK_RATIO = 0.32; // mark width as a fraction of the shorter canvas side

// Curated set of current device classes (CSS points, portrait orientation).
// Deliberately not the full historical Apple device list.
const DEVICES = [
	{ name: "iphone-16-pro-max", width: 430, height: 932, scale: 3 },
	{ name: "iphone-16-pro", width: 393, height: 852, scale: 3 },
	{ name: "iphone-16", width: 390, height: 844, scale: 3 },
	{ name: "iphone-16-plus", width: 428, height: 926, scale: 3 },
	{ name: "iphone-13-mini", width: 375, height: 812, scale: 3 },
	{ name: "iphone-11", width: 414, height: 896, scale: 2 },
	{ name: "iphone-se", width: 375, height: 667, scale: 2 },
	{ name: "ipad-10", width: 810, height: 1080, scale: 2 },
	{ name: "ipad-pro-11", width: 834, height: 1194, scale: 2 },
	{ name: "ipad-pro-12-9", width: 1024, height: 1366, scale: 2 },
];

function mediaQuery(width, height, scale, orientation) {
	return `(device-width: ${width}px) and (device-height: ${height}px) and (-webkit-device-pixel-ratio: ${scale}) and (orientation: ${orientation})`;
}

async function renderSplash(pxWidth, pxHeight, outFile) {
	const markSize = Math.round(Math.min(pxWidth, pxHeight) * MARK_RATIO);
	const mark = await sharp(MARK_SVG).resize(markSize, markSize).toBuffer();

	await sharp({
		create: {
			width: pxWidth,
			height: pxHeight,
			channels: 4,
			background: BACKGROUND,
		},
	})
		.composite([
			{
				input: mark,
				left: Math.round((pxWidth - markSize) / 2),
				top: Math.round((pxHeight - markSize) / 2),
			},
		])
		.png()
		.toFile(outFile);
}

const manifest = [];

async function main() {
	await mkdir(OUT_DIR, { recursive: true });

	for (const { name, width, height, scale } of DEVICES) {
		const portraitFile = `${name}-portrait.png`;
		await renderSplash(width * scale, height * scale, path.join(OUT_DIR, portraitFile));
		manifest.push({
			url: `/icons/splash/${portraitFile}`,
			media: mediaQuery(width, height, scale, "portrait"),
		});

		const landscapeFile = `${name}-landscape.png`;
		await renderSplash(height * scale, width * scale, path.join(OUT_DIR, landscapeFile));
		manifest.push({
			url: `/icons/splash/${landscapeFile}`,
			media: mediaQuery(width, height, scale, "landscape"),
		});
	}

	const source = `// Generated by scripts/generate-splash-screens.mjs — do not edit by hand.
export const APPLE_SPLASH_SCREENS: { url: string; media: string }[] = ${JSON.stringify(manifest, null, "\t")};
`;
	await writeFile(MANIFEST_OUT, source);

	console.log(`Generated ${manifest.length} splash screens in ${OUT_DIR}`);
	console.log(`Wrote manifest to ${MANIFEST_OUT}`);
}

main();
